"""chatToolsCreator.py — generate server/chatTools.py from the @mcp_tool routes.

AppCreator runs it right after mcpCreator, from the same specs
(mcpCreator.toolSpecs), so the chat route's tools and the MCP servers'
tools cannot drift. `python chatToolsCreator.py` regenerates it alone.

Per tool, chatTools.py holds:
  - <Tool>Args, a pydantic model of the tool's AI params (the route's
    params minus mcpTools.INJECTED_PARAMS), with the annotations and
    defaults mcpCreator writes into the MCP signatures. extra='ignore'
    drops a userId or storeId the model sends; hide_input_in_errors keeps
    a value out of a refusal. Its JSON schema title is the MCP SDK's
    (`<tool>Arguments`) and it has no docstring, so its schema is the one
    the MCP server lists;
  - _<tool>(userId, storeId, args), which runs the route through
    mcpRuntime.callRoute. userId always comes from the chat route's JWT;
    storeId is passed only to a route that takes one, from the
    conversation, never from the model;
  - TOOLS, each audience's tool list as Meta's chat API takes it, sorted by
    name: byte-stable, so Meta's prompt cache matches;
  - TOOL_CALLS, each audience's {name: (ArgsModel, call)}.

Refused (ValueError naming the route), besides mcpCreator's rules: a param
whose name a pydantic model cannot hold as a field (a BaseModel attribute,
or one starting with `model_`).
"""

import ast
import os

from pydantic import BaseModel

from mcpCreator import (INDENT, ToolSpec, callSource, toolSpecs,
                        writeIfChanged)
from mcpTools import MCP_AUDIENCES

SERVER_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_PATH = os.path.join(SERVER_DIR, 'chatTools.py')

HEADER = '''"""GENERATED by chatToolsCreator.py (AppCreator runs it): do not edit.

The tools of the chat route (actions/ChatActions.py, chatModel.runTool), one
list per audience, each a route marked @mcp_tool (mcpTools.py): the same
tools, descriptions and parameter schemas as mcpServer.py's.
"""
'''


def argsClassName(name: str) -> str:
    return f'{name[0].upper()}{name[1:]}Args'


def callFunctionName(name: str) -> str:
    return f'_{name}'


def _checkFieldNames(spec: ToolSpec) -> None:
    for param in spec.params:
        if hasattr(BaseModel, param.name) or param.name.startswith('model_'):
            raise ValueError(f'Chat tool {spec.name}: a param named '
                             f'{param.name} cannot be a pydantic field')


def _annotationImports(spec: ToolSpec) -> set:
    """The (module, name) imports the args model's annotations need: the
    spec's imports minus the responseModel, unless a param names it."""
    names = {
        node.id
        for param in spec.params
        for node in ast.walk(ast.parse(param.annotation, mode='eval'))
        if isinstance(node, ast.Name)
    }
    return {(module, name) for module, name in spec.imports if name in names}


def _argsSource(spec: ToolSpec) -> str:
    lines = [
        f'class {argsClassName(spec.name)}(BaseModel):',
        f'{INDENT}model_config = ConfigDict(extra=\'ignore\',',
        f'{INDENT}                          hide_input_in_errors=True,',
        f'{INDENT}                          title={spec.name + "Arguments"!r})',
    ]
    for p in spec.params:
        lines.append(f'{INDENT}{p.name}: {p.annotation}' +
                     ('' if p.default is None else f' = {p.default}'))
    return '\n'.join(lines)


def _callSource(spec: ToolSpec) -> str:
    arguments = ['userId=userId']
    if 'storeId' in spec.injected:
        arguments.append('storeId=storeId')
    arguments.append('**args.model_dump()')
    return '\n'.join([
        f'def {callFunctionName(spec.name)}(userId: str, storeId: str, '
        f'args: {argsClassName(spec.name)}) -> dict:',
        *callSource(spec.name, arguments),
    ])


def render(specs: list) -> str:
    """The source of chatTools.py for `specs`."""
    for spec in specs:
        _checkFieldNames(spec)
    importLines = sorted({
        f'from {module} import {name}'
        for spec in specs for module, name in _annotationImports(spec)
    })
    parts = [
        HEADER,
        'from pydantic import BaseModel, ConfigDict\n',
        'from ApiRequests import ApiRequests',
        'from mcpRuntime import callRoute',
        *importLines,
        '',
        'DESCRIPTIONS = {',
        *[f'    {spec.name!r}: {spec.description!r},' for spec in specs],
        '}',
    ]
    source = '\n'.join(parts) + '\n'
    for spec in specs:
        source += '\n\n' + _argsSource(spec) + '\n'
        source += '\n\n' + _callSource(spec) + '\n'
    source += '''

def _tool(name: str, argsModel: type[BaseModel]) -> dict:
    return {
        'type': 'function',
        'function': {
            'name': name,
            'description': DESCRIPTIONS[name],
            'parameters': argsModel.model_json_schema(by_alias=True),
        },
    }
'''
    source += '\n\nTOOL_CALLS = {\n'
    for audience in MCP_AUDIENCES:
        source += f'    {audience!r}: {{\n'
        for spec in specs:
            if audience in spec.audiences:
                source += (f'        {spec.name!r}: '
                           f'({argsClassName(spec.name)}, '
                           f'{callFunctionName(spec.name)}),\n')
        source += '    },\n'
    source += '}\n'
    source += '''
TOOLS = {
    audience: [_tool(name, argsModel)
               for name, (argsModel, _) in sorted(calls.items())]
    for audience, calls in TOOL_CALLS.items()
}
'''
    return source


def generatedSource() -> str:
    from ApiRequests import ApiRequests
    return render(toolSpecs(ApiRequests))


def write(source: str) -> bool:
    """Write chatTools.py; True when it changed."""
    return writeIfChanged(OUTPUT_PATH, source)


if __name__ == '__main__':
    changed = write(generatedSource())
    print('Generated chatTools.py' if changed else 'chatTools.py unchanged')

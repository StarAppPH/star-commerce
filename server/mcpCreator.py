"""mcpCreator.py — generate server/mcpServer.py from the @mcp_tool tools.

AppCreator runs it: validated with the routes, before any file is rewritten,
and written after app.py. `python mcpCreator.py` regenerates it alone;
test_mcp_server.py fails while it is stale.

Every method of ToolRequests marked @mcp_tool(<audience>, ...) (mcpTools.py)
becomes one tool function on each audience's MCPServer. The tool takes the
method's params minus mcpTools.INJECTED_PARAMS, with the same annotations
and defaults, and calls the tool method through mcpRuntime.callTool. Its
description is the method's docstring. Refused (ValueError naming the
tool):
  - a function carrying @route_config (httpMethod): a tool is no route;
  - a tool without a userId param (it always acts as the signed-in
    caller), or with a param named `ctx`;
  - a tool without a docstring: the AI picks tools by their description;
  - a tool whose responseModel is no ResponseModel all the way down: it is
    the tool's output schema;
  - a name outside TOOL_NAME_PATTERN (Meta's function-name rule, no dot);
  - an unannotated, *args or **kwargs param, or a default that is no plain
    literal (it is written into the generated file as its repr).
"""

import ast
import builtins
import inspect
import os
import re
import sys
import textwrap
from typing import NamedTuple

from mcpTools import INJECTED_PARAMS, MCP_AUDIENCES, MIN_THINKING_TEXTS
from responseModelCheck import assertResponseModel

SERVER_DIR = os.path.dirname(os.path.abspath(__file__))
OUTPUT_PATH = os.path.join(SERVER_DIR, 'mcpServer.py')
# Meta's Model API takes [a-zA-Z0-9_.-] with at most one dot; a tool name
# never needs the dot.
TOOL_NAME_PATTERN = re.compile(r'^[a-zA-Z0-9_-]{1,64}$')
CONTEXT_PARAM = 'ctx'
INDENT = '    '

HEADER = '''"""GENERATED by mcpCreator.py (AppCreator runs it): do not edit.

The MCP servers of starCommerce, one per audience, each tool a method of
ToolRequests marked @mcp_tool (mcpTools.py). Run locally beside Flask,
from the project root:

    ENVIRONMENT=localdev python server/mcpServer.py

Each server is at http://127.0.0.1:5004/<audience>/mcp and takes our JWT as
its bearer token (mcpRuntime.py).
"""
'''


class ToolParam(NamedTuple):
    name: str
    annotation: str
    default: str | None  # the default's repr, None when it has none


class ToolSpec(NamedTuple):
    name: str
    audiences: tuple
    description: str
    params: tuple  # ToolParam, the ones the AI passes
    injected: tuple  # the INJECTED_PARAMS the tool takes, in order
    returns: str  # the tool's responseModel: its output schema
    imports: tuple  # (module, name) the annotations and returns need
    thinkingText: tuple  # what the chat shows while it runs (mcpTools)


def mcpTools(toolRequestsClass) -> dict:
    """Every method of `toolRequestsClass` marked @mcp_tool, by name."""
    return {
        name: func
        for name, func in inspect.getmembers(toolRequestsClass,
                                             inspect.isfunction)
        if getattr(func, 'mcpAudiences', None)
    }


def _refuse(name: str, problem: str):
    raise ValueError(f'MCP tool {name}: {problem}')


def _functionDef(original) -> ast.FunctionDef:
    tree = ast.parse(textwrap.dedent(inspect.getsource(original)))
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            return node
    raise ValueError(f'No function definition in {original.__name__}')


def _annotationImports(name: str, annotation: ast.expr, globalsOf: dict):
    """The (module, name) imports an annotation's names need: builtins need
    none, anything else is imported from the module that defines it, or,
    for a name whose defining module does not hold it (a type alias such as
    `StoreCurrency = Literal[...]` reports typing), from the tool's own
    module, whose globals hold it."""
    imports = []
    for node in ast.walk(annotation):
        if isinstance(node, ast.Attribute):
            _refuse(name, f'write `{ast.unparse(node)}` as a bare name '
                    'imported into the tool module')
        if not isinstance(node, ast.Name) or hasattr(builtins, node.id):
            continue
        if node.id not in globalsOf:
            _refuse(name, f'annotation name {node.id} is not defined')
        value = globalsOf[node.id]
        module = getattr(value, '__module__', None)
        if module is None or getattr(sys.modules.get(module), node.id,
                                     None) is not value:
            module = globalsOf.get('__name__')
        if module in (None, '__main__'):
            _refuse(name, f'annotation name {node.id} cannot be imported')
        imports.append((module, node.id))
    return imports


def _literalRepr(name: str, param: str, value) -> str:
    text = repr(value)
    try:
        roundTrip = ast.literal_eval(text)
    except (ValueError, SyntaxError):
        roundTrip = object()
    if roundTrip != value or type(roundTrip) is not type(value):
        _refuse(name, f'the default of {param} is no plain literal')
    return text


def toolSpec(name: str, func) -> ToolSpec:
    """The tool a marked method becomes, after checking every rule."""
    audiences = tuple(func.mcpAudiences)
    if any(audience not in MCP_AUDIENCES for audience in audiences):
        _refuse(name, f'audiences {audiences} are not all in {MCP_AUDIENCES}')
    if any(getattr(f, 'httpMethod', None)
           for f in (func, inspect.unwrap(func))):
        _refuse(name, 'carries @route_config: a tool is no route')
    if not TOOL_NAME_PATTERN.match(name):
        _refuse(name, f'the name must match {TOOL_NAME_PATTERN.pattern}')
    responseModel = getattr(func, 'responseModel', None)
    if not isinstance(responseModel, type):
        _refuse(name, 'needs a responseModel: it is the output schema')
    try:
        assertResponseModel(name, responseModel)
    except ValueError as problem:
        _refuse(name, str(problem))
    thinkingText = getattr(func, 'mcpThinkingText', ())
    if len(thinkingText) < MIN_THINKING_TEXTS:
        _refuse(name, f'needs at least {MIN_THINKING_TEXTS} thinkingText')
    original = inspect.unwrap(func)
    description = inspect.getdoc(original)
    if not description or not description.strip():
        _refuse(name, 'needs a docstring: it is the tool description')

    signature = inspect.signature(original)
    definition = _functionDef(original)
    annotations = {
        arg.arg: arg.annotation
        for arg in definition.args.args + definition.args.kwonlyargs
    }
    params, injected, imports = [], [], []
    for param in signature.parameters.values():
        if param.name in ('self', 'cls'):
            continue
        if param.kind in (param.VAR_POSITIONAL, param.VAR_KEYWORD):
            _refuse(name, f'*{param.name} params cannot be tool arguments')
        if param.name == CONTEXT_PARAM:
            _refuse(name, f'a param named {CONTEXT_PARAM} would shadow the '
                    'MCP context')
        if param.name in INJECTED_PARAMS:
            injected.append(param.name)
            continue
        annotation = annotations.get(param.name)
        if annotation is None:
            _refuse(name, f'param {param.name} needs a type annotation')
        imports += _annotationImports(name, annotation, original.__globals__)
        default = (None if param.default is inspect.Parameter.empty else
                   _literalRepr(name, param.name, param.default))
        params.append(ToolParam(param.name, ast.unparse(annotation), default))
    if 'userId' not in injected:
        _refuse(name, 'needs a userId param: the caller it acts as')
    imports.append((responseModel.__module__, responseModel.__name__))
    return ToolSpec(name, audiences, description, tuple(params),
                    tuple(injected), responseModel.__name__,
                    tuple(sorted(set(imports))), tuple(thinkingText))


def toolSpecs(toolRequestsClass) -> list:
    return [
        toolSpec(name, func)
        for name, func in sorted(mcpTools(toolRequestsClass).items())
    ]


_INJECTED_SOURCE = {
    'userId': 'callerUserId()',
    'storeId': f'sessionStoreId({CONTEXT_PARAM})',
}


def callSource(toolName: str, arguments: list) -> list:
    """The lines of a generated tool's body: `return callTool(...)` of
    the tool method `toolName` with `arguments` (each `name=source`), one
    per line. chatToolsCreator writes the same call."""
    lines = [f'{INDENT}return callTool(ToolRequests().{toolName},']
    for i, argument in enumerate(arguments):
        end = ')' if i == len(arguments) - 1 else ','
        lines.append(f'{INDENT}                {argument}{end}')
    return lines


def _toolSource(spec: ToolSpec) -> str:
    lines = [
        f"@servers[{audience!r}].tool(name={spec.name!r}, "
        f"description=DESCRIPTIONS[{spec.name!r}], structured_output=True)"
        for audience in spec.audiences
    ]
    signature = [f'{CONTEXT_PARAM}: Context'] + [
        f'{p.name}: {p.annotation}' +
        ('' if p.default is None else f' = {p.default}')
        for p in spec.params
    ]
    lines.append(f'def {spec.name}({", ".join(signature)}) -> {spec.returns}:')
    arguments = [f'{param}={_INJECTED_SOURCE[param]}'
                 for param in spec.injected
                 ] + [f'{p.name}={p.name}' for p in spec.params]
    lines += callSource(spec.name, arguments)
    return '\n'.join(lines)


def render(specs: list) -> str:
    """The source of mcpServer.py for `specs`."""
    importLines = sorted({
        f'from {module} import {name}'
        for spec in specs for module, name in spec.imports
    })
    parts = [
        HEADER,
        'from mcp.server.mcpserver import Context\n',
        'from ToolRequests import ToolRequests',
        'from mcpRuntime import (callTool, callerUserId, newServer, run,',
        '                        sessionStoreId)',
        *importLines,
        '',
        'servers = {',
        *[f'    {audience!r}: newServer({audience!r}),'
          for audience in MCP_AUDIENCES],
        '}',
        '',
        'DESCRIPTIONS = {',
        *[f'    {spec.name!r}: {spec.description!r},' for spec in specs],
        '}',
    ]
    source = '\n'.join(parts) + '\n'
    for spec in specs:
        source += '\n\n' + _toolSource(spec) + '\n'
    source += "\n\nif __name__ == '__main__':\n    run(servers)\n"
    return source


def generatedSource() -> str:
    from ToolRequests import ToolRequests
    return render(toolSpecs(ToolRequests))


def writeIfChanged(path: str, source: str) -> bool:
    """Write `source` to `path` unless it already holds it; True when it
    changed."""
    try:
        with open(path, encoding='utf-8') as f:
            if f.read() == source:
                return False
    except FileNotFoundError:
        pass
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(source)
    return True


def write(source: str) -> bool:
    """Write mcpServer.py; True when it changed."""
    return writeIfChanged(OUTPUT_PATH, source)


if __name__ == '__main__':
    changed = write(generatedSource())
    print('Generated mcpServer.py' if changed else 'mcpServer.py unchanged')

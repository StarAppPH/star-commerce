def _isEmptyLiteral(node) -> bool:
    """`{}` or `[]`: the fallback that replaces a None."""
    return (isinstance(node, ast.Dict) and not node.keys) or (isinstance(node, ast.List) and not node.elts)


# Unrolling limits: the items of one module constant, and the element
# evaluations of one comprehension (its generators' product). Past them the
# loop variable is unknown, so its reads show as dynamicKey.
MAX_CONSTANT_ITEMS = 64
MAX_COMPREHENSION_ITEMS = 256
# Methods that change a list, set or dict in place.
_MUTATORS = frozenset({'append', 'extend', 'insert', 'update', 'add', 'remove', 'discard', 'pop', 'clear',
                       'setdefault', 'sort', 'reverse', 'popitem', 'difference_update', 'intersection_update',
                       'symmetric_difference_update'})


# Calls that only read (iterate, measure or copy) what is passed to them.
_READING_CALLS = frozenset({'len', 'iter', 'sorted', 'list', 'tuple', 'set', 'frozenset', 'enumerate', 'zip',
                            'reversed', 'any', 'all', 'sum', 'min', 'max', 'join'})


def _isMutable(expr) -> bool:
    """A list, set or dict literal (bare or through list()/set()/dict())."""
    return isinstance(expr, (ast.List, ast.Set, ast.Dict)) or (
        isinstance(expr, ast.Call) and finalName(expr.func) in ('list', 'set', 'dict'))


def _escapes(node, parent) -> bool:
    """Whether this use of a value may hand it to code that changes it: any
    use but iterating, comparing, indexing, an attribute (a mutating method
    is caught on its own), unpacking, arithmetic, an f-string or a reading
    call. Assigning it to another name, an argument default, returning it or
    passing it to any other call all escape."""
    if isinstance(parent, (ast.For, ast.AsyncFor, ast.comprehension)):
        return parent.iter is not node
    if isinstance(parent, ast.Call):
        return parent.func is node or finalName(parent.func) not in _READING_CALLS
    return not isinstance(parent, (ast.Compare, ast.Subscript, ast.Attribute, ast.Starred, ast.BinOp,
                                   ast.UnaryOp, ast.FormattedValue, ast.Expr))


def _mutatedValues(repo: Repo) -> set:
    """(module, line, column) of every module-level value that code anywhere
    in the repo may change: a mutating method call on it, an augmented, item
    or attribute assignment to it, a del of an item, or a rebinding through
    `global`; and a list, set or dict that escapes to other code (_escapes),
    which could change it under another name. A name that only shadows it
    locally counts too (no proof)."""
    out = set()
    for module in repo.modules.values():
        parents = {id(child): node for node in ast.walk(module.tree) for child in ast.iter_child_nodes(node)}
        for node in ast.walk(module.tree):
            if isinstance(node, (ast.Name, ast.Attribute)) and isinstance(node.ctx, ast.Load) \
                    and _escapes(node, parents.get(id(node))):
                found = repo.resolveExpr(module, node)
                if found and found[0] == 'value' and _isMutable(found[2]):
                    out.add((found[1].rel, found[2].lineno, found[2].col_offset))
            targets = []
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr in _MUTATORS:
                targets.append(node.func.value)
            elif isinstance(node, ast.AugAssign):
                targets.append(node.target)
            elif isinstance(node, (ast.Assign, ast.Delete)):
                targets += [t.value if isinstance(t, ast.Subscript) else t for t in node.targets
                            if isinstance(t, (ast.Subscript, ast.Attribute))]
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                declared = {n for g in ast.walk(node) if isinstance(g, ast.Global) for n in g.names}
                targets += [t for a in ast.walk(node) if isinstance(a, (ast.Assign, ast.AnnAssign))
                            for t in (a.targets if isinstance(a, ast.Assign) else [a.target])
                            if isinstance(t, ast.Name) and t.id in declared]
            for t in targets:
                while isinstance(t, ast.Subscript):
                    t = t.value
                found = repo.resolveExpr(module, t) if isinstance(t, (ast.Name, ast.Attribute)) else None
                if found and found[0] == 'value':
                    out.add((found[1].rel, found[2].lineno, found[2].col_offset))
    return out



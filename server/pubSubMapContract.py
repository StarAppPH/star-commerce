# The first line of every server/objects_<publisher>.py pubSubModels.py
# generates. A model defined in one is its publisher's own payload schema, so
# the map does not expand its fields (_expandModel; see the module docs, 3.).
GENERATED_MODELS_HEADER = '# GENERATED by server/pubSubModels.py. Do not edit.'
_GENERATED_MODELS_FILE = re.compile(r'objects_[A-Za-z_][A-Za-z0-9_]*\.py')


def isGeneratedModels(rel: str, text: str) -> bool:
    """True for a top-level server/objects_<identifier>.py (`rel` is
    server-relative) whose first line, of `text` (normalised as
    pubSubMapScan.normaliseSource does: no BOM, LF), is
    GENERATED_MODELS_HEADER."""
    return _GENERATED_MODELS_FILE.fullmatch(rel) is not None and text.split('\n', 1)[0] == GENERATED_MODELS_HEADER



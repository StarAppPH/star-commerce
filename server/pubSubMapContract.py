"""Resolve what each Pub/Sub push handler reads from its message.

An abstract interpreter over a handler's AST (pubSubMapScan.py supplies the
module index, name resolution and pydantic models). It starts with the
handler's first parameter bound to the payload root and follows the value
through:

1. subscripts, .get(), `in` probes and iteration (a list element is `[]`);
2. sub-dicts bound to locals, and the parameter rebound to a sub-key;
3. pydantic parses (`Model(**p)`, `Model.model_validate(p)`): every field of
   the model becomes a requirement at that path, nested models recursively.
   A model defined in a generated objects_<publisher>.py (pubSubModels.py)
   is the publisher's own payload schema, kept fresh by its own tests: its
   parse is one requirement (the model row) and its fields are not expanded;
   what the handler reads off it and forwards (8.) still is;
4. plain wrapper classes holding the dict (`__init__` and the methods it calls);
5. repo helper functions and methods, to depth MAX_CALL_DEPTH;
6. `self.<otherHandler>(p)` delegation;
7. dict fields of a parsed model re-parsed later (loops and comprehensions
   over a literal, or over a module constant holding a literal tuple, list
   or set of strings, are unrolled; getattr with a constant name is
   followed);
8. methods and properties of a parsed model, and values forwarded into a model
   constructor (`Model(k=p['x'])`), which type the path by that field. A
   sub-model (or a list of them) read off a parsed model keeps its field's
   nullability: an attribute, an iteration or a model_dump() of one that may
   be None needs it non-null, and forwarding one types its path like a
   forwarded value;
9. raw key reads. A subscript, .get() or .pop() whose key cannot be resolved
   is a `dynamicKey` requirement at the parent path: shown, never checked.

Guards: a straight-line read after an early return on a value check stays
unconditional (a truthiness test such as `if p.get('k'):` is a value check);
a presence guard on the same value (`if x:`, `if x is None: return`,
`x if x else None`) makes reads of that value `ifPresent`; only a `'k' in p`
test whose branch returns marks what follows as the "k absent" branch
(`deadBranch`, decided against the publisher in the join); reads inside a
`try` whose `except Exception` (or bare `except`) does not raise again are
`lenient`, which is shown but suppresses nothing (the handler would drop the
message silently). A model field accepts null only when every before, wrap
or plain validator of it provably turns None into a value (`noneToValue`,
see mapsNoneToValue).

Requirement.toJson / Requirement.fromJson are the map's row form and its
inverse (with parsePath and parseType), so a snapshot section stands in for
an absent consumer with nothing lost.

Pure stdlib, Python 3.10 compatible, byte-identical in every repo.
"""
from __future__ import annotations


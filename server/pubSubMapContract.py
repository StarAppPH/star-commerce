class Requirement:
    """One thing a handler relies on at a payload path."""
    # The boolean flags; the map stores the ones that are set.
    FLAGS = ('required', 'nonNull', 'hasDefault', 'ifPresent', 'lenient', 'noneToValue',
             'unverifiable')
    __slots__ = ('path', 'kind', 'model', 'forwardedTo', 'required', 'nonNull', 'hasDefault',
                 'ifPresent', 'lenient', 'deadBranch', 'via', 'ctype', 'noneToValue',
                 'unverifiable', 'forbidKeys', 'typeUnknown')

    def __init__(self, path, kind='key', model=None, forwardedTo=None, required=False,
                 nonNull=False, hasDefault=False, via='', ctype=None, noneToValue=False,
                 unverifiable=False, forbidKeys=None):
        self.path, self.kind, self.model, self.forwardedTo = path, kind, model, forwardedTo
        self.required, self.nonNull, self.hasDefault = required, nonNull, hasDefault
        self.ifPresent, self.lenient, self.deadBranch = False, False, None
        self.via = {via} if via else set()
        self.ctype, self.noneToValue = ctype, noneToValue
        self.unverifiable, self.forbidKeys = unverifiable, forbidKeys
        self.typeUnknown = False  # from the map, with a type that cannot be checked

    def copy(self) -> 'Requirement':
        out = Requirement.__new__(Requirement)
        for slot in self.__slots__:
            setattr(out, slot, getattr(self, slot))
        out.via = set(self.via)
        return out

    def identity(self) -> tuple:
        return rowIdentity(self.toJson())

    def toJson(self) -> dict:
        """The map's form: false flags and empty values are left out, and so
        is `via` (provenance, with file:line; `--explain` prints it live)."""
        out = {'path': pathText(self.path)}
        if pathAltKeys(self.path):
            out['altKeys'] = pathAltKeys(self.path)
        if self.kind != 'key':
            out['kind'] = self.kind
        for name in ('model', 'forwardedTo', 'deadBranch'):
            if getattr(self, name):
                out[name] = getattr(self, name)
        for name in self.FLAGS:
            if getattr(self, name):
                out[name] = True
        if self.ctype is not None:
            out['consumerType'] = printType(self.ctype)
        if self.forbidKeys is not None:
            out['extraForbid'] = sorted(self.forbidKeys)  # the keys the model accepts
        return out

    @classmethod
    def fromJson(cls, row: dict) -> 'Requirement':
        """toJson's inverse, for a requirement read from the map (a snapshot
        section). Only a type that cannot be checked from the row (a
        consumerType edited by hand, or an older map's `extraForbid: true`
        without the keys) sets typeUnknown."""
        req = cls(parsePath(row['path'], row.get('altKeys')), kind=row.get('kind', 'key'),
                  model=row.get('model'), forwardedTo=row.get('forwardedTo'))
        for name in cls.FLAGS:
            setattr(req, name, bool(row.get(name)))
        req.deadBranch = row.get('deadBranch')
        req.ctype = parseType(row['consumerType']) if row.get('consumerType') else None
        forbid = row.get('extraForbid')
        keys = isinstance(forbid, list) and all(isinstance(k, str) for k in forbid)
        req.forbidKeys = tuple(forbid) if keys else (() if forbid else None)
        req.typeUnknown = bool(forbid and not keys) or (bool(row.get('consumerType')) and req.ctype is None)
        return req


# What makes two requirement rows (a handler requirement, a flow row) the same
# requirement, with the value a row leaves out: everything else (flags, types,
# provenance) describes it.
ROW_IDENTITY = {'path': None, 'kind': 'key', 'model': '', 'forwardedTo': '', 'ifPresent': False,
                'lenient': False, 'deadBranch': ''}
ROW_IDENTITY_KEYS = tuple(ROW_IDENTITY)


def rowIdentity(row: dict) -> tuple:
    return tuple(row[k] if default is None else (row.get(k) or default) for k, default in ROW_IDENTITY.items())


def parsePath(text: str, altKeys=None) -> tuple:
    """pathText's inverse: 'items[].unit._id' -> ('items', '[]', 'unit',
    '_id'); '(root)' -> (). `altKeys` (a requirement's per-segment
    alternatives) rebuilds alias segments."""
    out = []
    if text not in ('', ROOT):
        for part in text.split('.'):
            while part.endswith('[]'):
                part = part[:-2]
                out += ([part] if part else []) + ['[]']
                part = ''
            if part:
                out.append(part)
    if altKeys:
        out = [tuple([seg, *alts]) if alts else seg for seg, alts in zip(out, altKeys)]
    return tuple(out)


_PRINTED = {'any': ANY, 'list': ('list', ANY), 'dict': ('dict', ANY)}
_PRINTED_SCALARS = frozenset({'str', 'int', 'float', 'bool', 'datetime', 'date'})
_LITERAL_VALUES = (str, int, float, bool, bytes, type(None))


def parseType(text: str):
    """printType's inverse, for a consumerType read from the map: scalars,
    Literal and Enum values (`[...]`: none known), lists, dicts and unions;
    any other name is an opaque model. None for anything else, including a
    hand-edited string that is not a printed type."""
    try:
        return _parsedType(ast.parse(text, mode='eval').body)
    except (SyntaxError, ValueError, TypeError, RecursionError, MemoryError):
        return None


def _parsedType(node):
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        return union([_parsedType(node.left), _parsedType(node.right)])
    if isinstance(node, ast.Constant) and node.value is None:
        return NONE
    if isinstance(node, ast.Name):
        if node.id in _PRINTED:
            return _PRINTED[node.id]
        return (node.id,) if node.id in _PRINTED_SCALARS else ('model', None, node.id)
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name):
        name, inner = node.value.id, node.slice
        if name == 'list':
            return ('list', _parsedType(inner))
        if name == 'dict' and isinstance(inner, ast.Tuple) and len(inner.elts) == 2:
            return ('dict', _parsedType(inner.elts[1]))
        elts = inner.elts if isinstance(inner, ast.Tuple) else [inner]
        if len(elts) == 1 and isinstance(elts[0], ast.Constant) and elts[0].value is Ellipsis:
            elts = []
        values = tuple(ast.literal_eval(e) for e in elts)
        if not all(isinstance(v, _LITERAL_VALUES) for v in values):
            raise ValueError('a Literal or Enum value that is not a scalar')
        return ('lit', values) if name == 'Literal' else ('enum', name, values)
    raise ValueError(f'not a printed type: {type(node).__name__}')


def mergeRequirements(reqs) -> list:
    """One requirement per identity (path, kind, model, forwardedTo and the
    guard flags); required/nonNull are OR-ed, hasDefault AND-ed, via unioned."""
    merged = {}
    for r in reqs:
        key = r.identity()
        if key not in merged:
            merged[key] = r.copy()
            continue
        m = merged[key]
        m.required = m.required or r.required
        m.nonNull = m.nonNull or r.nonNull
        m.hasDefault = m.hasDefault and r.hasDefault
        m.noneToValue = m.noneToValue and r.noneToValue
        m.unverifiable = m.unverifiable or r.unverifiable
        m.via |= r.via
        if m.ctype is None:
            m.ctype = r.ctype
    return [r for k, r in sorted(merged.items()) if not _subsumed(r, merged.values())]


def _subsumed(r, others) -> bool:
    """A plain key read is implied by another requirement at the same path,
    under the same guards, that is at least as strict."""
    if r.kind != 'key' or r.forwardedTo:
        return False
    return any(o is not r and o.kind != 'dynamicKey' and _norm(o.path) == _norm(r.path)
               and o.ifPresent == r.ifPresent
               and o.lenient == r.lenient and o.deadBranch == r.deadBranch
               and (o.required or not r.required) and (o.nonNull or not r.nonNull)
               and (r.hasDefault or not o.hasDefault) for o in others)


class _Ctx:
    __slots__ = ('guards', 'absent', 'lenient')

    def __init__(self, guards=frozenset(), absent=frozenset(), lenient=False):
        self.guards, self.absent, self.lenient = guards, absent, lenient

    def but(self, **changes) -> '_Ctx':
        values = {s: getattr(self, s) for s in self.__slots__}
        values.update(changes)
        return _Ctx(**values)


class _Frame:
    __slots__ = ('module', 'env', 'cls', 'returns', 'depth', 'self')

    def __init__(self, module, env, cls, depth, selfValue=None):
        self.module, self.env, self.cls, self.depth = module, env, cls, depth
        self.returns, self.self = [], selfValue


def _carries(v, depth=0) -> bool:
    """True when `v` holds (part of) the payload."""
    if depth > 4 or v is None:
        return False
    if isinstance(v, _P):
        return True
    if isinstance(v, _M):
        return v.path is not None
    if isinstance(v, _W):
        return any(_carries(x, depth + 1) for x in v.attrs.values())
    if isinstance(v, _D):
        return any(_carries(x, depth + 1) for x in [*v.items.values(), *v.spreads])
    if isinstance(v, _T):
        return any(_carries(x, depth + 1) for x in v.items)
    if isinstance(v, _S):
        return _carries(v.elem, depth + 1)
    return False


def _sig(v):
    if v is None:
        return 'U'
    if isinstance(v, _P):
        return ('P', v.path, v.required, v.hasDefault, v.coalesced)
    if isinstance(v, _M):
        return ('M', v.ci.key, v.path, v.nullable, v.required, v.hasDefault)
    if isinstance(v, _S):
        return ('S', _sig(v.elem), v.path, v.nullable, v.required, v.hasDefault)
    if isinstance(v, _W):
        return ('W', v.ci.key, tuple(sorted((k, _sig(x)) for k, x in v.attrs.items())))
    if isinstance(v, _D):
        return ('D', tuple(sorted((k, _sig(x)) for k, x in v.items.items())),
                tuple(_sig(x) for x in v.spreads))
    if isinstance(v, _T):
        return ('T', tuple(_sig(x) for x in v.items))
    if isinstance(v, _L):
        return ('L', repr(v.value))
    if isinstance(v, _H):
        return 'H'
    return 'O'


class ContractResolver:
    """Resolves handler contracts for one repo; analyses are memoised by
    (function, binding signature, remaining depth) and recorded context-free,
    so a helper shared by many handlers is analysed once."""

    def __init__(self, repo: Repo):
        self.repo = repo
        self._memo, self._modelMemo, self._active = {}, {}, set()
        self._mutated = None
        self._out = None
        self.truncated = False

    def _global(self, found):
        """A resolved global as a value: a module-level literal tuple, list or
        set of strings (bare, or wrapped in frozenset/set/tuple/list) becomes
        its items, so loops over it unroll, unless it has more than
        MAX_CONSTANT_ITEMS or code anywhere may change it; anything else
        stays a reference."""
        if found is None:
            return None
        expr = found[2] if found[0] == 'value' else None
        if isinstance(expr, ast.Call) and finalName(expr.func) in ('frozenset', 'set', 'tuple', 'list') \
                and len(expr.args) == 1 and not expr.keywords:
            expr = expr.args[0]
        if not (isinstance(expr, (ast.Tuple, ast.List, ast.Set)) and len(expr.elts) <= MAX_CONSTANT_ITEMS
                and all(isinstance(e, ast.Constant) and isinstance(e.value, str) for e in expr.elts)):
            return _R(found)
        if self._mutated is None:
            self._mutated = _mutatedValues(self.repo)
        if (found[1].rel, found[2].lineno, found[2].col_offset) in self._mutated:
            return _R(found)
        return _T([_L(e.value) for e in expr.elts])

    # ---- entry point -------------------------------------------------------
    def handlerContract(self, handlerCi: ClassInfo, module: Module, node) -> tuple:
        """(requirements, truncated) for one handler method."""
        self._out, self.truncated = [], False
        params = [a.arg for a in node.args.args]
        env = {}
        if params:
            env[params[0]] = _H(handlerCi)
        if len(params) > 1:
            env[params[1]] = _P(())
        frame = _Frame(module, env, handlerCi, 0, env.get(params[0]) if params else None)
        self._block(node.body, frame, _Ctx())
        return mergeRequirements(self._out), self.truncated

    # ---- events ------------------------------------------------------------
    def _emit(self, req: Requirement, ctx: _Ctx) -> None:
        req.ifPresent = _norm(req.path) in ctx.guards
        req.lenient = ctx.lenient
        if ctx.absent:
            req.deadBranch = ', '.join(sorted(pathText(p) for p in ctx.absent))
        self._out.append(req)

    def _read(self, path, ctx, via, required=True, hasDefault=False):
        self._emit(Requirement(path, required=required, hasDefault=hasDefault, via=via), ctx)

    def _dynamicKey(self, v, ctx, via):
        """A key of the payload at `v` is read, but which one the analysis
        cannot tell: recorded so the read is visible, never checked."""
        self._emit(Requirement(v.path, kind='dynamicKey', via=via), ctx)

    def _use(self, v, ctx, how):
        """`v` is subscripted, iterated, unpacked or attribute-accessed, so a
        None there would raise: it must be non-null (unless guarded). A model
        or list of models read off a parsed model counts when its field may be
        None."""
        if isinstance(v, _P):
            used = not v.coalesced
        else:
            used = isinstance(v, (_M, _S)) and v.nullable
        if used and v.path and _norm(v.path) not in ctx.guards:
            self._emit(Requirement(v.path, required=v.required, hasDefault=v.hasDefault,
                                   nonNull=True, via=how), ctx)

    def _modelReq(self, ci: ClassInfo, path, ctx, via, exclude=frozenset()):
        """A pydantic parse of the payload at `path`: the model itself, then
        every constraining field, nested models recursively."""
        key = (ci.key, path, exclude)
        if key not in self._modelMemo:
            saved, self._out = self._out, []
            self._expandModel(ci, path, exclude, frozenset(), True)
            self._modelMemo[key], self._out = self._out, saved
        label = _located(f'parse:{ci.name}', ci.module, ci.node) if via in ('', None) else via
        for req in self._modelMemo[key]:
            r = req.copy()
            r.via = {label}
            self._emit(r, ctx)

    def _expandModel(self, ci, path, exclude, stack, nonNullHere):
        repo = self.repo
        info = repo.modelInfo(ci)
        forbid = info.acceptedKeys() if info.extra == 'forbid' else None
        self._out.append(Requirement(path, kind='model', model=ci.anchor, nonNull=nonNullHere,
                                     forbidKeys=forbid))
        if isGeneratedModels(ci.module.rel, ci.module.text):
            return  # the publisher's own schema: see the module docs (3.)
        if info.rootType is not None:
            self._expandType(info.rootType, path, stack | {ci.key})
            return
        for f in info.fields.values():
            if f.computed or set(f.inKeys) & exclude:
                continue
            fpath = path + (fieldSegment(f),)
            base = nonNull(f.type)
            constraining = (f.required or not f.nullable or literalValues(f.type) is not None
                            or _hasInt(base) or base[0] in ('model', 'list'))
            if constraining:
                self._out.append(Requirement(
                    fpath, forwardedTo=f'{ci.anchor}.{f.name}', required=f.required,
                    nonNull=not f.nullable, hasDefault=not f.required, ctype=f.type,
                    noneToValue=mapsNoneToValue(f.beforeValidators, f.type, f.constrained, self.repo),
                    unverifiable=f.unverifiable))
            self._expandType(f.type, fpath, stack | {ci.key})

    def _expandType(self, t, path, stack):
        base = nonNull(t)
        sub = self.repo.modelOfType(base)
        if sub is not None and sub.ci.key not in stack:
            self._expandModel(sub.ci, path, frozenset(), stack, not isNullable(t))
        elif base[0] == 'list':
            sub = self.repo.modelOfType(nonNull(base[1]))
            if sub is not None and sub.ci.key not in stack:
                self._expandModel(sub.ci, path + ('[]',), frozenset(), stack, not isNullable(base[1]))

    def _forward(self, v, ci: ClassInfo, field, ctx, via):
        """`v` is passed as `field` of model `ci` (a kwarg or a literal dict
        entry): the field's type and nullability apply at v's path."""
        if field is None:
            return
        if isinstance(v, (_P, _M, _S)) and v.path:
            coalesced = isinstance(v, _P) and v.coalesced
            self._emit(Requirement(v.path, forwardedTo=f'{ci.anchor}.{field.name}',
                                   required=v.required, hasDefault=v.hasDefault,
                                   nonNull=not field.nullable and not coalesced, via=via,
                                   ctype=field.type,
                                   noneToValue=mapsNoneToValue(field.beforeValidators, field.type,
                                                               field.constrained, self.repo),
                                   unverifiable=field.unverifiable), ctx)
            sub = self.repo.modelOfType(field.type)
            if sub is not None:
                self._modelReq(sub.ci, v.path, ctx.but(guards=ctx.guards | {_norm(v.path)})
                               if field.nullable else ctx, via)
            elif nonNull(field.type)[0] == 'list':
                elem = self.repo.modelOfType(nonNull(field.type)[1])
                if elem is not None:
                    self._modelReq(elem.ci, v.path + ('[]',), ctx, via)
        elif isinstance(v, _D):
            sub = self.repo.modelOfType(field.type)
            if sub is not None:
                self._construct(sub.ci, [], v.items, [], ctx, via)

    def _construct(self, ci, args, kws, stars, ctx, via):
        """Model(**X) / Model(k=v) / Model.model_validate(X)."""
        info = self.repo.modelInfo(ci)
        label = via or _located(f'forward:{ci.name}', ci.module, ci.node)
        if info.rootType is not None:
            target = args[0] if args else kws.get('root')
            if isinstance(target, _P):
                self._modelReq(ci, target.path, ctx, via)
                return _M(ci, target.path)
            return None
        byKey = {}
        for f in info.fields.values():
            for k in (*f.inKeys, f.name):
                byKey.setdefault(k, f)
        for star in stars:
            if isinstance(star, _P):
                self._use(star, ctx, 'unpack')
                self._modelReq(ci, star.path, ctx, via, frozenset(kws))
                if not kws:
                    return _M(ci, star.path)
            elif isinstance(star, _D):
                kws = {**star.items, **kws}
        attrs = {}
        for key, value in kws.items():
            f = byKey.get(key)
            self._forward(value, ci, f, ctx, label)
            if f is not None:
                attrs[f.name] = value
        return _W(ci, attrs)

    # ---- statements --------------------------------------------------------
    def _block(self, body, frame, ctx) -> bool:
        """Run a statement list; True when it always leaves (return, raise,
        continue, break). Early exits narrow the guards of what follows."""
        for stmt in body:
            result = self._stmt(stmt, frame, ctx)
            if result is True:
                return True
            if isinstance(result, _Ctx):
                ctx = result
        return False

    def _stmt(self, s, frame, ctx):
        if isinstance(s, ast.Return):
            v = self._ev(s.value, frame, ctx) if s.value is not None else _L(None)
            frame.returns.append(v)
            return True
        if isinstance(s, ast.Raise):
            if s.exc is not None:
                self._ev(s.exc, frame, ctx)
            return True
        if isinstance(s, (ast.Continue, ast.Break)):
            return True
        if isinstance(s, ast.Expr):
            self._ev(s.value, frame, ctx)
        elif isinstance(s, ast.Assign):
            v = self._ev(s.value, frame, ctx)
            for target in s.targets:
                self._bind(target, v, frame, ctx)
        elif isinstance(s, ast.AnnAssign):
            if s.value is not None:
                self._bind(s.target, self._ev(s.value, frame, ctx), frame, ctx)
        elif isinstance(s, ast.AugAssign):
            self._ev(s.value, frame, ctx)
            if isinstance(s.target, ast.Name):
                frame.env[s.target.id] = None
        elif isinstance(s, ast.If):
            return self._if(s, frame, ctx)
        elif isinstance(s, (ast.For, ast.AsyncFor)):
            it = self._ev(s.iter, frame, ctx)
            if isinstance(it, _T):
                for item in it.items:
                    self._bind(s.target, item, frame, ctx)
                    self._block(s.body, frame, ctx)
            else:
                self._bind(s.target, self._elementOf(it, ctx, 'iterate'), frame, ctx)
                self._block(s.body, frame, ctx)
            self._block(s.orelse, frame, ctx)
        elif isinstance(s, ast.While):
            self._cond(s.test, frame, ctx)
            self._block(s.body, frame, ctx)
            self._block(s.orelse, frame, ctx)
        elif isinstance(s, (ast.With, ast.AsyncWith)):
            for item in s.items:
                self._ev(item.context_expr, frame, ctx)
                if item.optional_vars is not None:
                    self._bind(item.optional_vars, None, frame, ctx)
            return self._block(s.body, frame, ctx)
        elif isinstance(s, ast.Try):
            lenient = ctx.lenient or any(_catchesAll(h) for h in s.handlers)
            left = self._block(s.body, frame, ctx.but(lenient=lenient))
            handlersLeave = True
            for h in s.handlers:
                if h.name:
                    frame.env[h.name] = None
                handlersLeave = self._block(h.body, frame, ctx) and handlersLeave
            self._block(s.orelse, frame, ctx)
            self._block(s.finalbody, frame, ctx)
            return left and handlersLeave
        elif isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef)):
            env = dict(frame.env)
            for a in [*s.args.posonlyargs, *s.args.args, *s.args.kwonlyargs]:
                env[a.arg] = None
            inner = _Frame(frame.module, env, frame.cls, frame.depth, frame.self)
            self._block(s.body, inner, ctx)
            frame.env[s.name] = _Fn(s)
        elif isinstance(s, (ast.Import, ast.ImportFrom)):
            for alias in s.names:
                if alias.name != '*':
                    local = alias.asname or alias.name.split('.')[0]
                    frame.env[local] = self._localImport(frame.module, s, alias)
        elif isinstance(s, ast.Assert):
            pos, _, _, _ = self._cond(s.test, frame, ctx)
            return ctx.but(guards=ctx.guards | pos)
        return None

    def _localImport(self, module, s, alias):
        if isinstance(s, ast.Import):
            target = self.repo.byName.get(alias.name)
            return _R(('module', target)) if target else None
        source = module._absolute(s.module, s.level)
        target = self.repo.byName.get(source)
        found = self.repo.resolveName(target, alias.name) if target else None
        return _R(found) if found else None

    def _if(self, s, frame, ctx):
        pos, neg, disc, _ = self._cond(s.test, frame, ctx)
        bodyLeaves = self._block(s.body, frame, ctx.but(guards=ctx.guards | pos))
        elseLeaves = self._block(s.orelse, frame, ctx.but(guards=ctx.guards | neg))
        if bodyLeaves and elseLeaves:
            return True
        if bodyLeaves:
            return ctx.but(guards=ctx.guards | neg, absent=ctx.absent | disc)
        if elseLeaves:
            return ctx.but(guards=ctx.guards | pos)
        return None

    def _cond(self, test, frame, ctx):
        """Evaluate a test; return (paths known present when it is true, paths
        known present when it is false, discriminator paths known absent when
        it is false, the test's own value)."""
        if isinstance(test, ast.UnaryOp) and isinstance(test.op, ast.Not):
            pos, neg, _, _ = self._cond(test.operand, frame, ctx)
            return neg, pos, _EMPTY, None
        if isinstance(test, ast.BoolOp):
            pos, neg, disc = _EMPTY, _EMPTY, _EMPTY
            inner = ctx
            for value in test.values:
                p, n, d, _ = self._cond(value, frame, inner)
                if isinstance(test.op, ast.And):
                    pos, inner = pos | p, inner.but(guards=inner.guards | p)
                else:
                    neg, disc, inner = neg | n, disc | d, inner.but(guards=inner.guards | n)
            return pos, neg, (_EMPTY if isinstance(test.op, ast.And) else disc), None
        if isinstance(test, ast.Compare) and len(test.ops) == 1:
            left = self._ev(test.left, frame, ctx)
            right = self._ev(test.comparators[0], frame, ctx)
            op = test.ops[0]
            if isinstance(op, (ast.In, ast.NotIn)) and isinstance(right, _P) and isinstance(left, _L) \
                    and isinstance(left.value, str):
                self._use(right, ctx, 'in')
                path = right.path + (left.value,)
                self._read(path, ctx, 'in', required=False)
                if isinstance(op, ast.In):
                    return frozenset({_norm(path)}), _EMPTY, frozenset({_norm(path)}), None
                return _EMPTY, frozenset({_norm(path)}), _EMPTY, None
            isNone = isinstance(test.comparators[0], ast.Constant) and test.comparators[0].value is None
            if isinstance(left, (_P, _M, _S)) and left.path and isNone:
                if isinstance(op, (ast.IsNot, ast.NotEq)):
                    return frozenset({_norm(left.path)}), _EMPTY, _EMPTY, None
                if isinstance(op, (ast.Is, ast.Eq)):
                    return _EMPTY, frozenset({_norm(left.path)}), _EMPTY, None
            return _EMPTY, _EMPTY, _EMPTY, None
        if isinstance(test, ast.Compare):
            self._ev(test.left, frame, ctx)
            for c in test.comparators:
                self._ev(c, frame, ctx)
            return _EMPTY, _EMPTY, _EMPTY, None
        if isinstance(test, ast.Call) and finalName(test.func) == 'isinstance' and test.args:
            v = self._ev(test.args[0], frame, ctx)
            for a in test.args[1:]:
                self._ev(a, frame, ctx)
            if isinstance(v, (_P, _M, _S)) and v.path:
                return frozenset({_norm(v.path)}), _EMPTY, _EMPTY, None
            return _EMPTY, _EMPTY, _EMPTY, None
        v = self._ev(test, frame, ctx)
        if isinstance(v, (_P, _M, _S)) and v.path:
            # a presence guard on v, but not a discriminator: a falsy value
            # does not mean the publisher omitted the key
            return frozenset({_norm(v.path)}), _EMPTY, _EMPTY, v
        return _EMPTY, _EMPTY, _EMPTY, v

    def _bind(self, target, v, frame, ctx):
        if isinstance(target, ast.Name):
            frame.env[target.id] = v
        elif isinstance(target, (ast.Tuple, ast.List)):
            items = v.items if isinstance(v, _T) and len(v.items) == len(target.elts) else None
            for i, elt in enumerate(target.elts):
                self._bind(elt, items[i] if items else None, frame, ctx)
        elif isinstance(target, ast.Attribute):
            owner = self._ev(target.value, frame, ctx)
            if isinstance(owner, _W):
                owner.attrs[target.attr] = v
        elif isinstance(target, ast.Subscript):
            self._use(self._ev(target.value, frame, ctx), ctx, 'write')
            self._ev(target.slice, frame, ctx)
        elif isinstance(target, ast.Starred):
            self._bind(target.value, None, frame, ctx)

    # ---- expressions -------------------------------------------------------
    def _ev(self, node, frame, ctx):
        if node is None:
            return None
        if isinstance(node, ast.Name):
            if node.id in frame.env:
                return frame.env[node.id]
            found = self.repo.resolveName(frame.module, node.id)
            if found is None and node.id[:1].isupper():
                ci = self.repo.classByName(node.id) if node.id not in _SKIP_GLOBALS else None
                found = ('class', ci) if ci else None
            return self._global(found)
        if isinstance(node, ast.Constant):
            return _L(node.value)
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, (ast.USub, ast.UAdd)) \
                and isinstance(node.operand, ast.Constant) and type(node.operand.value) in (int, float):
            return _L(-node.operand.value if isinstance(node.op, ast.USub) else node.operand.value)
        if isinstance(node, ast.Subscript):
            return self._subscript(node, frame, ctx)
        if isinstance(node, ast.Attribute):
            return self._attribute(self._ev(node.value, frame, ctx), node.attr, frame, ctx)
        if isinstance(node, ast.Call):
            return self._call(node, frame, ctx)
        if isinstance(node, ast.BoolOp):
            return self._boolop(node, frame, ctx)
        if isinstance(node, ast.IfExp):
            pos, neg, _, _ = self._cond(node.test, frame, ctx)
            body = self._ev(node.body, frame, ctx.but(guards=ctx.guards | pos))
            orelse = self._ev(node.orelse, frame, ctx.but(guards=ctx.guards | neg))
            if isinstance(body, _P) and _isEmptyLiteral(node.orelse):
                # `x if <test of x> else {}` replaces a None, as `x or {}` does; under a
                # test of something else, x itself is used whenever the test holds
                return _P(body.path, body.required, True, True) if body.path and _norm(body.path) in pos else body
            return body if isinstance(orelse, _L) and orelse.value is None else None
        if isinstance(node, ast.Compare):
            self._cond(node, frame, ctx)
            return None
        if isinstance(node, ast.Dict):
            items, spreads = {}, []
            for k, value in zip(node.keys, node.values):
                v = self._ev(value, frame, ctx)
                if k is None:
                    self._use(v, ctx, 'unpack')
                    spreads.append(v)
                else:
                    key = self._ev(k, frame, ctx)
                    if isinstance(key, _L) and isinstance(key.value, str):
                        items[key.value] = v
            return _D(items, spreads)
        if isinstance(node, (ast.List, ast.Tuple, ast.Set)):
            return _T([self._ev(e, frame, ctx) for e in node.elts])
        if isinstance(node, (ast.ListComp, ast.SetComp, ast.GeneratorExp, ast.DictComp)):
            return self._comprehension(node, frame, ctx)
        if isinstance(node, ast.NamedExpr):
            v = self._ev(node.value, frame, ctx)
            self._bind(node.target, v, frame, ctx)
            return v
        if isinstance(node, ast.Starred):
            return self._ev(node.value, frame, ctx)
        if isinstance(node, ast.Lambda):
            return None
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.expr):
                self._ev(child, frame, ctx)
        return None

    def _boolop(self, node, frame, ctx):
        """`a and b`, `a or b`: later operands run under the earlier ones'
        guards. `x or {}` / `x or []` is x with a None already replaced."""
        values, inner, last = [], ctx, len(node.values) - 1
        for i, value in enumerate(node.values):
            if i < last:
                pos, neg, _, v = self._cond(value, frame, inner)
                inner = inner.but(guards=inner.guards | (pos if isinstance(node.op, ast.And) else neg))
            else:
                v = self._ev(value, frame, inner)
            values.append(v)
        if isinstance(node.op, ast.Or) and len(values) == 2 and isinstance(values[0], _P) \
                and _isEmptyLiteral(node.values[-1]):
            return _P(values[0].path, values[0].required, True, True)
        return None

    def _comprehension(self, node, frame, ctx):
        env = dict(frame.env)
        self._generators(node, node.generators, _Frame(frame.module, env, frame.cls, frame.depth, frame.self),
                         ctx, MAX_COMPREHENSION_ITEMS)
        return None

    def _generators(self, node, gens, inner, guards, budget: int):
        """The comprehension's generators from `gens` on, then its element; a
        literal iterable (_T) is unrolled, as a for loop over one is, while
        the product of the unrolled sizes stays within `budget`."""
        if not gens:
            for part in ((node.key, node.value) if isinstance(node, ast.DictComp) else (node.elt,)):
                self._ev(part, inner, guards)
            return
        gen = gens[0]
        it = self._ev(gen.iter, inner, guards)
        unroll = isinstance(it, _T) and len(it.items) <= budget
        for item in it.items if unroll else [self._elementOf(it, guards, 'iterate')]:
            self._bind(gen.target, item, inner, guards)
            narrowed = guards
            for cond in gen.ifs:
                pos, _, _, _ = self._cond(cond, inner, narrowed)
                narrowed = narrowed.but(guards=narrowed.guards | pos)
            self._generators(node, gens[1:], inner, narrowed, budget // max(len(it.items), 1) if unroll else budget)

    def _elementOf(self, it, ctx, how):
        if isinstance(it, _P):
            self._use(it, ctx, how)
            return _P(it.path + ('[]',))
        if isinstance(it, _S):
            self._use(it, ctx, how)
            return it.elem
        if isinstance(it, _M):
            info = self.repo.modelInfo(it.ci)
            if info.rootType is not None:
                return self._elementOf(self._typedValue(info.rootType, it.path), ctx, how)
        return None

    def _subscript(self, node, frame, ctx):
        v = self._ev(node.value, frame, ctx)
        k = self._ev(node.slice, frame, ctx)
        if isinstance(v, _P):
            self._use(v, ctx, 'subscript')
            if isinstance(k, _L) and isinstance(k.value, str):
                path = v.path + (k.value,)
                self._read(path, ctx, 'subscript')
                return _P(path)
            if isinstance(k, _L) and isinstance(k.value, int):
                return _P(v.path + ('[]',))
            if isinstance(node.slice, ast.Slice):
                return _P(v.path)
            self._dynamicKey(v, ctx, f'subscript[{ast.unparse(node.slice)}]')
            return None
        if isinstance(v, _D) and isinstance(k, _L):
            return v.items.get(k.value)
        if isinstance(v, _T) and isinstance(k, _L) and isinstance(k.value, int):
            return v.items[k.value] if -len(v.items) <= k.value < len(v.items) else None
        if isinstance(v, _S):
            self._use(v, ctx, 'subscript')
            return v.elem if not isinstance(node.slice, ast.Slice) else v
        return None

    def _typedValue(self, t, path, required=True, hasDefault=False):
        """The value a model attribute of type `t` holds for payload `path`
        (a sub-model, or a list of them, keeps the field's nullability)."""
        base = nonNull(t)
        sub = self.repo.modelOfType(base)
        if sub is not None:
            return _M(sub.ci, path, isNullable(t), required, hasDefault)
        if base[0] == 'list':
            elem = self.repo.modelOfType(nonNull(base[1]))
            if elem is not None:
                return _S(_M(elem.ci, path + ('[]',), isNullable(base[1])), path, isNullable(t), required,
                          hasDefault)
        return _P(path, required, hasDefault)

    def _attribute(self, v, attr, frame, ctx):
        repo = self.repo
        if isinstance(v, _M):
            self._use(v, ctx, 'attr')
            info = repo.modelInfo(v.ci)
            if attr == 'root' and info.rootType is not None:
                return self._typedValue(info.rootType, v.path)
            f = info.fields.get(attr)
            if f is not None and not f.computed:
                return self._typedValue(f.type, v.path + (fieldSegment(f),), f.required, f.hasDefault)
            return self._methodValue(v, v.ci, attr, frame, ctx)
        if isinstance(v, _W):
            if attr in v.attrs:
                return v.attrs[attr]
            return self._methodValue(v, v.ci, attr, frame, ctx)
        if isinstance(v, _H):
            found = repo.methodOf(v.ci, attr)
            return _BM(v, found, attr) if found else None
        if isinstance(v, _P):
            self._use(v, ctx, 'attr')
            return _BM(v, None, attr)
        if isinstance(v, _R):
            ref = v.ref
            if ref[0] == 'class':
                found = repo.member(ref[1], attr)
                return _BM(v, found, attr) if found and found[0] == 'func' else (
                    self._global(found) if found else _BM(v, None, attr))
            if ref[0] == 'module':
                return self._global(repo.resolveName(ref[1], attr))
            if ref[0] == 'ext':
                return _R(('ext', f'{ref[1]}.{attr}'))
        return None

    def _methodValue(self, recv, ci, attr, frame, ctx):
        found = self.repo.methodOf(ci, attr)
        if found is None:
            return _BM(recv, None, attr)
        node = found[2]
        if any(finalName(d) in ('property', 'cached_property', 'computed_field')
               for d in node.decorator_list):
            return self._invoke(found, recv, [], {}, frame, ctx, f'method:{ci.name}.{attr}')
        return _BM(recv, found, attr)

    # ---- calls -------------------------------------------------------------
    def _call(self, node, frame, ctx):
        callee = self._ev(node.func, frame, ctx)
        args, stars = [], []
        for a in node.args:
            v = self._ev(a.value if isinstance(a, ast.Starred) else a, frame, ctx)
            args.append(v)
        kws = {}
        for kw in node.keywords:
            v = self._ev(kw.value, frame, ctx)
            if kw.arg is None:
                stars.append(v)
            else:
                kws[kw.arg] = v
        name = finalName(node.func)
        if isinstance(callee, _BM):
            return self._callMethod(callee, args, kws, stars, frame, ctx)
        if isinstance(callee, _R):
            ref = callee.ref
            if ref[0] == 'class':
                return self._callClass(ref[1], args, kws, stars, frame, ctx)
            if ref[0] == 'func':
                return self._invoke(ref, None, args, kws, frame, ctx, f'helper:{ref[1].rel}::{ref[2].name}')
            if ref[0] == 'ext' and ref[1].rsplit('.', 1)[-1] == 'deepcopy' and args:
                return args[0]
            if ref[0] == 'ext':
                for s in stars:
                    self._use(s, ctx, 'unpack')
                return None
        if isinstance(callee, _Fn):
            return None
        return self._builtin(name if isinstance(node.func, ast.Name) else None, args, kws, stars,
                             frame, ctx)

    def _builtin(self, name, args, kws, stars, frame, ctx):
        for s in stars:
            self._use(s, ctx, 'unpack')
        first = args[0] if args else None
        iterating = name in ('dict', 'list', 'sorted', 'set', 'tuple', 'reversed', 'deepcopy')
        if iterating and isinstance(first, (_P, _S)):
            if name != 'dict' or not kws:
                self._use(first, ctx, 'iterate')
                return first
        if name == 'len' and isinstance(first, (_P, _S)):
            self._use(first, ctx, 'len')
        if name == 'enumerate' and first is not None:
            return _S(_T([None, self._elementOf(first, ctx, 'iterate')]))
        if name == 'getattr' and len(args) >= 2 and isinstance(args[1], _L) and isinstance(args[1].value, str):
            return self._attribute(first, args[1].value, frame, ctx)
        if name == 'dict' and not args and kws:
            return _D(kws, [])
        return None

    def _callMethod(self, bm, args, kws, stars, frame, ctx):
        recv, ref, name = bm.recv, bm.ref, bm.name
        if isinstance(recv, _P) and ref is None:
            if name in ('get', 'pop') and args and isinstance(args[0], _L) and isinstance(args[0].value, str):
                path = recv.path + (args[0].value,)
                default = args[1] if len(args) > 1 else kws.get('default')
                hasDefault = default is not None and not (isinstance(default, _L) and default.value is None)
                required = name == 'pop' and len(args) == 1
                self._read(path, ctx, name, required=required, hasDefault=hasDefault)
                return _P(path, required, hasDefault)
            if name in ('get', 'pop') and args:
                self._dynamicKey(recv, ctx, name)
                return None
            if name in ('items', 'keys', 'values'):
                return _DYN
            if name == 'copy':
                return recv
            return None
        if isinstance(recv, _R) and recv.ref[0] == 'class':
            ci = recv.ref[1]
            if ref is None:
                if name in ('model_validate', 'parse_obj', 'validate') and self.repo.isModel(ci):
                    return self._construct(ci, [], {}, args[:1], ctx, None) if isinstance(
                        args[0] if args else None, (_P, _D)) else None
                return None
            if ref[0] == 'func':
                return self._invoke(ref, None, args, kws, frame, ctx,
                                    f'method:{ref[3].name if ref[3] else ci.name}.{name}', static=True)
            return None
        if ref is None:
            if isinstance(recv, _M) and name in ('model_dump', 'dict') and recv.path is not None:
                return _P(recv.path, recv.required, recv.hasDefault)  # the model's payload, as a dict
            return None
        if isinstance(recv, _H) and _isRoute(ref[2]):
            # self.<otherHandler>(data): that handler's own contract, so it
            # runs at this handler's depth rather than one level deeper
            return self._invoke(ref, recv, args, kws, frame, ctx, f'delegate:{name}', sameDepth=True)
        return self._invoke(ref, recv, args, kws, frame, ctx,
                            f'method:{ref[3].name if ref[3] else "?"}.{name}')

    def _callClass(self, ci, args, kws, stars, frame, ctx):
        repo = self.repo
        if repo.isModel(ci):
            return self._construct(ci, args, kws, stars, ctx, None)
        if repo.isEnum(ci):
            return None
        init = repo.methodOf(ci, '__init__')
        for s in stars:
            self._use(s, ctx, 'unpack')
        if init is None or init[3] is None or not any(_carries(v) for v in [*args, *kws.values()]):
            return None
        w = _W(ci)
        self._invoke(init, w, args, kws, frame, ctx, f'wrapper:{ci.name}')
        return w

    def _invoke(self, ref, selfValue, args, kws, frame, ctx, label, static=False, sameDepth=False):
        """Analyse a repo function/method with its parameters bound; replay
        its (memoised, context-free) requirements in the caller's context."""
        module, node, owner = ref[1], ref[2], ref[3]
        depth = (frame.depth if frame else 0) + (0 if sameDepth else 1)
        if not any(_carries(v) for v in [*args, *kws.values(), selfValue]):
            return None
        if depth > MAX_CALL_DEPTH:
            self.truncated = True
            return None
        decorators = {finalName(d) for d in node.decorator_list}
        params = [a.arg for a in [*node.args.posonlyargs, *node.args.args]]
        isClassMethod = 'classmethod' in decorators
        bindSelf = (owner is not None and params and 'staticmethod' not in decorators
                    and (not static or isClassMethod))
        selfName = params[0] if bindSelf else None
        if bindSelf:
            params = params[1:]
        env = {p: None for p in params + [a.arg for a in node.args.kwonlyargs]}
        for p, v in zip(params, args):
            env[p] = v
        for k, v in kws.items():
            if k in env:
                env[k] = v
        bound = selfValue if selfName and not isClassMethod and isinstance(selfValue, _W) else None
        if selfName:
            env[selfName] = None if isClassMethod else selfValue
        key = (module.rel, node.lineno, node.name, tuple(sorted((k, _sig(v)) for k, v in env.items())),
               MAX_CALL_DEPTH - depth)
        if key in self._active:
            return None
        entry = self._memo.get(key)
        if entry is None:
            self._active.add(key)
            saved, savedTrunc = self._out, self.truncated
            self._out, self.truncated = [], False
            inner = _Frame(module, env, owner, depth, selfValue)
            self._block(node.body, inner, _Ctx())
            attrs = dict(bound.attrs) if bound is not None else None
            entry = (self._out, self._returnValue(inner.returns), attrs, self.truncated)
            self._memo[key] = entry
            self._out, self.truncated = saved, savedTrunc
            self._active.discard(key)
        reqs, result, attrs, truncated = entry
        self.truncated = self.truncated or truncated
        label = _located(label, module, node)
        if attrs is not None and bound is not None:
            bound.attrs.update(attrs)
        for req in reqs:
            r = req.copy()
            r.via = {label}
            r.ifPresent = r.ifPresent or _norm(r.path) in ctx.guards
            r.lenient = r.lenient or ctx.lenient
            if ctx.absent and not r.deadBranch:
                r.deadBranch = ', '.join(sorted(pathText(p) for p in ctx.absent))
            self._out.append(r)
        return result

    @staticmethod
    def _returnValue(returns):
        values = [v for v in returns if not (isinstance(v, _L) and v.value is None)]
        sigs = {_sig(v) for v in values}
        if len(sigs) == 1 and isinstance(values[0], (_P, _M, _W, _D, _S)):
            return values[0]
        return None


_EMPTY = frozenset()
_SKIP_GLOBALS = frozenset({'True', 'False', 'None'})


def _located(label: str, module: Module, node) -> str:
    return f'{label} (server/{module.rel}:{node.lineno})'


def _catchesAll(handler: ast.ExceptHandler) -> bool:
    """`except Exception` / `except BaseException` / bare `except` that
    swallows the error: one that raises again (re-raise or raise ... from)
    does not make the try body lenient."""
    names = [finalName(t) for t in (handler.type.elts if isinstance(handler.type, ast.Tuple)
                                    else [handler.type])] if handler.type is not None else ['Exception']
    reraises = any(isinstance(n, ast.Raise) for n in ownStatements(handler.body))
    return ('Exception' in names or 'BaseException' in names) and not reraises


def _norm(path: tuple) -> tuple:
    """A path with alias segments reduced to their printed key, for guard and
    subsumption comparisons."""
    return tuple(segKeys(seg)[0] for seg in path)


def fieldSegment(f):
    """The path segment of a model field: its key, or (primary, *others)
    when pydantic accepts it under more than one key."""
    return f.inKeys[0] if len(f.inKeys) == 1 else tuple(f.inKeys)


def _isRoute(node) -> bool:
    return any(finalName(d) == 'route_config' for d in node.decorator_list)


def _hasInt(t) -> bool:
    members = t[1] if t[0] == 'union' else (t,)
    return any(m[0] == 'int' or (m[0] == 'list' and _hasInt(nonNull(m[1]))) for m in members)


# ----------------------------------------------------------------------------
# Before validators: does None come out as a value of the field's type?
# ----------------------------------------------------------------------------

# Calls that return a value of their own name's kind, never None (given
# arguments that do not raise).
_VALUE_CALLS = frozenset({'str', 'int', 'float', 'bool', 'list', 'dict', 'set', 'tuple', 'frozenset',
                          'Decimal'})
_LITERAL_KINDS = {ast.JoinedStr: 'str', ast.List: 'list', ast.ListComp: 'list', ast.Tuple: 'tuple',
                  ast.Set: 'set', ast.SetComp: 'set', ast.Dict: 'dict', ast.DictComp: 'dict'}
# The value kinds a scalar field type accepts (a Literal, Enum or date field
# needs more than a kind, so nothing proves it). An empty literal container
# has its own kind ('emptyList', ...): only it fits a typed list or dict,
# and only an empty dict fits a model (one that needs nothing).
_SCALAR_FITS = {'str': {'str'}, 'int': {'int'}, 'float': {'int', 'float', 'Decimal'}, 'bool': {'bool'}}
_EMPTY_KINDS = {'emptyList': 'list', 'emptyTuple': 'tuple', 'emptySet': 'set', 'emptyDict': 'dict'}
# isinstance targets that None is known not to be an instance of.
_KNOWN_CLASSES = frozenset({'str', 'int', 'float', 'bool', 'bytes', 'list', 'dict', 'set', 'tuple',
                            'frozenset', 'Decimal', 'datetime', 'date'})
# What the validator's value holds: None, anything, or (any other state) a
# value of that kind.
_IS_NONE, _UNKNOWN = 'none', 'unknown'


def mapsNoneToValue(validators, ftype, constrained: bool, repo) -> bool:
    """Every validator def in `validators` (a field's before, wrap or plain
    validators) provably turns None into a value of the field type `ftype`
    (never for a `constrained` field: a fallback is no proof it passes):
    called with None, it returns e.g. `if v is None: return ''`,
    `if v is None: v = []` then `return v`, `return v or 0`,
    `return '' if v is None else v`. A raise, a use of the value that would
    fail on None, a test or a call the analysis cannot decide, a rebinding of
    the value it cannot follow, a value of another type, or falling off the
    end keeps the field non-null."""
    return bool(validators) and not constrained and all(
        _fits(_noneResult(fn), ftype, repo) for fn in validators)


def _noneResult(fn):
    """The kind of value `fn` returns when called with None, or None when
    that is not provably a value."""
    params = [a.arg for a in fn.args.posonlyargs + fn.args.args]
    if params and params[0] in ('cls', 'self'):
        params = params[1:]
    if not params:
        return None
    outcome, kind = _runOnNone(fn.body, params[0], _IS_NONE)
    return kind if outcome == 'return' else None


def _fits(kind, t, repo) -> bool:
    members = t[1] if t[0] == 'union' else (t,)
    return kind is not None and any(_fitsMember(kind, m, repo) for m in members)


def _fitsMember(kind, t, repo) -> bool:
    base, empty = _EMPTY_KINDS.get(kind, kind), kind in _EMPTY_KINDS
    if t == ANY or base in _SCALAR_FITS.get(t[0], ()):
        return True
    if t[0] == 'list':
        return base in ('list', 'tuple', 'set', 'frozenset') and (empty or t[1] == ANY)
    if t[0] == 'dict':
        return base == 'dict' and (empty or t[1] == ANY)
    info = repo.modelOfType(t) if t[0] == 'model' and repo is not None else None
    return kind == 'emptyDict' and info is not None and info.rootType is None and not info.modelValidated \
        and not any(f.required for f in info.fields.values())


def _runOnNone(stmts, v: str, state: str) -> tuple:
    """Run `stmts` for a validator called with None in `v`, holding `state`:
    ('return', kind) when they return or stop (kind None: not provably a
    value), ('next', state) when they fall through."""
    for s in stmts:
        if isinstance(s, ast.Return):
            return 'return', _kindOf(s.value, v, state) if s.value is not None else None
        if isinstance(s, ast.If):
            taken = _takesBody(s.test, v, state)
            if taken is None:
                return 'return', None
            outcome, state = _runOnNone(s.body if taken else s.orelse, v, state)
            if outcome == 'return':
                return outcome, state
        elif isinstance(s, (ast.Assign, ast.AnnAssign)) and any(
                isinstance(t, ast.Name) and t.id == v
                for t in (s.targets if isinstance(s, ast.Assign) else [s.target])):
            if s.value is None:
                continue
            kind = _kindOf(s.value, v, state)
            if kind is None and not _noneSafe(s.value, v, state):
                return 'return', None
            isNone = isinstance(s.value, ast.Constant) and s.value.value is None
            state = kind or (_IS_NONE if isNone else _UNKNOWN)
        elif any(isinstance(n, (ast.Return, ast.Raise)) or (isinstance(n, ast.Name) and n.id == v and (
                not isinstance(n.ctx, ast.Load) or state in (_IS_NONE, _UNKNOWN))) for n in ast.walk(s)):
            return 'return', None  # a rebinding (or a None use) this walk does not follow
    return 'next', state


def _kindOf(e, v: str, state: str):
    """The kind ('str', 'int', 'list', ...) of the value `e` evaluates to
    without raising, or None when it may be None, may raise or is unknown."""
    if isinstance(e, ast.IfExp):  # only the branch taken is evaluated
        taken = _takesBody(e.test, v, state)
        if taken is not None:
            return _kindOf(e.body if taken else e.orelse, v, state)
        kinds = {_kindOf(e.body, v, state), _kindOf(e.orelse, v, state)}
        return kinds.pop() if len(kinds) == 1 and _noneSafe(e.test, v, state) else None
    if isinstance(e, ast.BoolOp) and isinstance(e.op, ast.Or):  # the first truthy operand, else the last
        kinds = {_kindOf(x, v, state) for x in e.values[:-1]
                 if not (isinstance(x, ast.Name) and x.id == v and state == _IS_NONE)}
        kinds.add(_kindOf(e.values[-1], v, state))
        return kinds.pop() if len(kinds) == 1 else None
    if not _noneSafe(e, v, state):
        return None
    if isinstance(e, ast.Constant):
        return None if e.value is None else type(e.value).__name__
    if isinstance(e, ast.Name):
        return state if e.id == v and state not in (_IS_NONE, _UNKNOWN) else None
    if isinstance(e, (ast.List, ast.Tuple, ast.Set)) and not e.elts or isinstance(e, ast.Dict) and not e.keys:
        return 'empty' + _LITERAL_KINDS[type(e)].capitalize()
    if type(e) in _LITERAL_KINDS:
        return _LITERAL_KINDS[type(e)]
    if isinstance(e, ast.Call) and finalName(e.func) in _VALUE_CALLS and (
            state not in (_IS_NONE, _UNKNOWN) or not any(
                isinstance(n, ast.Name) and n.id == v for a in e.args + e.keywords for n in ast.walk(a))):
        name = finalName(e.func)
        empty = 'empty' + name.capitalize()
        return empty if empty in _EMPTY_KINDS and not e.args and not e.keywords else name
    return None


def _isNoneType(node) -> bool:
    return (isinstance(node, ast.Constant) and node.value is None) or finalName(node) == 'NoneType' or (
        isinstance(node, ast.Call) and finalName(node.func) == 'type' and len(node.args) == 1
        and isinstance(node.args[0], ast.Constant) and node.args[0].value is None)


def _takesBody(test, v: str, state: str):
    """Whether an if-test is true (True) or false (False) given `state`, or
    None when that is not decided (always, for an unknown value)."""
    if state == _UNKNOWN or not _noneSafe(test, v, state):
        return None
    isNone = state == _IS_NONE
    if isinstance(test, ast.UnaryOp) and isinstance(test.op, ast.Not):
        inner = _takesBody(test.operand, v, state)
        return None if inner is None else not inner
    if isinstance(test, ast.BoolOp):
        stop = isinstance(test.op, ast.Or)  # Or stops at a true operand, And at a false one
        for operand in test.values:
            taken = _takesBody(operand, v, state)
            if taken is None or taken == stop:
                return taken
        return not stop
    if isinstance(test, ast.Name) and test.id == v:
        return False if isNone else None
    if isinstance(test, ast.Call) and finalName(test.func) == 'isinstance' and len(test.args) == 2 \
            and isinstance(test.args[0], ast.Name) and test.args[0].id == v:
        classes = test.args[1].elts if isinstance(test.args[1], ast.Tuple) else [test.args[1]]
        if not isNone:
            return None
        if any(_isNoneType(c) for c in classes):
            return True
        known = all(isinstance(c, (ast.Name, ast.Attribute)) and finalName(c) in _KNOWN_CLASSES for c in classes)
        return False if known else None
    if not (isinstance(test, ast.Compare) and len(test.ops) == 1):
        return None
    left, op, right = test.left, test.ops[0], test.comparators[0]
    if isinstance(right, ast.Name) and right.id == v and isinstance(op, (ast.Is, ast.IsNot, ast.Eq, ast.NotEq)):
        left, right = right, left
    if not (isinstance(left, ast.Name) and left.id == v):
        return None
    if isinstance(op, (ast.Is, ast.IsNot, ast.Eq, ast.NotEq)) and isinstance(right, ast.Constant):
        if right.value is not None and not isNone:
            return None
        same = isNone and right.value is None
        return same if isinstance(op, (ast.Is, ast.Eq)) else not same
    if isinstance(op, (ast.In, ast.NotIn)) and isinstance(right, (ast.Tuple, ast.List, ast.Set)) \
            and isNone and all(isinstance(e, ast.Constant) for e in right.elts):
        found = any(e.value is None for e in right.elts)
        return found if isinstance(op, ast.In) else not found
    return None


def _noneSafe(e, v: str, state: str) -> bool:
    """Evaluating `e` cannot raise because the value may be None: every use
    of it is a bare operand of a None-safe comparison, a boolean, a
    conditional, an f-string, a container element or keyed dict value, or
    isinstance (or the value is known not to be None)."""
    if state not in (_IS_NONE, _UNKNOWN):
        return True
    parents = {id(child): node for node in ast.walk(e) for child in ast.iter_child_nodes(node)}
    for n in ast.walk(e):
        if not (isinstance(n, ast.Name) and n.id == v) or n is e:
            continue
        parent = parents[id(n)]
        if isinstance(parent, ast.Compare):
            ok = all(isinstance(op, (ast.Is, ast.IsNot, ast.Eq, ast.NotEq)) or (
                isinstance(op, (ast.In, ast.NotIn)) and isinstance(c, (ast.Tuple, ast.List, ast.Set)))
                for op, c in zip(parent.ops, parent.comparators))
        elif isinstance(parent, ast.Call):
            ok = finalName(parent.func) == 'isinstance' and parent.args[:1] == [n]
        elif isinstance(parent, ast.Dict):  # `{**v}` unpacks it: only a keyed entry is safe
            ok = not any(k is None and val is n for k, val in zip(parent.keys, parent.values))
        else:
            ok = isinstance(parent, (ast.BoolOp, ast.IfExp, ast.Tuple, ast.List, ast.Set)) or (
                isinstance(parent, ast.UnaryOp) and isinstance(parent.op, ast.Not)) or (
                isinstance(parent, ast.FormattedValue) and parent.format_spec is None)
        if not ok:
            return False
    return True

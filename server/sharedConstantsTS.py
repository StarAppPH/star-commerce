"""sharedConstants.py's public values as TypeScript (renderSharedConstantsTS).

sharedConstants.py is the single source of truth for values both the server
and the browser need. Everything public in it is copied verbatim into the
client's lib/generated/serverConstants.ts (AppCreator.writeSharedConstantsTS
writes the file) — there is no registry to keep in sync, so the guards below
are what stop a secret or an unserializable value from riding along.

Pure: it imports sharedConstants and nothing of the app, so
`python AppCreator.py --constants-only` works on a bare checkout.
"""
import json
import re
import types
from typing import Any

import sharedConstants

_TS_BANNER = """/* eslint-disable */
/**
 * This file was automatically generated by server/AppCreator.py.
 * DO NOT MODIFY IT BY HAND. Instead, modify server/sharedConstants.py, and
 * run `cd server && python AppCreator.py --constants-only` to regenerate
 * this file.
 */
"""

_TS_NAME_RE = re.compile(r'^[A-Za-z_$][A-Za-z0-9_$]*$')

# TS reserved words that are perfectly legal Python names. Without these the
# generator would emit uncompilable TS instead of an actionable error.
_TS_RESERVED = {
    'var', 'let', 'const', 'function', 'new', 'this', 'typeof', 'enum',
    'interface', 'default', 'export', 'extends', 'switch', 'case', 'do',
    'catch', 'delete', 'instanceof', 'void', 'throw', 'debugger', 'static',
    'public', 'package', 'null', 'true', 'false', 'super', 'implements',
    'protected', 'await',
}

# Matched against the top-level SCREAMING_SNAKE name, word-delimited on
# purpose: an unanchored TOKEN would block MAX_TOKENS and an unanchored KEY
# would block DEFAULT_SORT_KEY, and there is no allowlist to escape with.
# TOKENS is deliberately only blocked behind an ACCESS/AUTH/REFRESH/BEARER
# qualifier, because this repo runs AI agents and MAX_TOKENS is plausible.
_SECRETISH_RE = re.compile(
    r'(^|_)(SECRETS?|TOKEN|PASSWORDS?|PASSWD|CREDENTIALS?|PRIVATE|SALT'
    r'|SIGNATURES?|BEARER|PIN|OTP)(_|$)'
    r'|(^|_)(ACCESS|AUTH|REFRESH|BEARER)_TOKENS(_|$)'
    r'|(^|_)(API|SECRET|PRIVATE|SIGNING|ENCRYPTION|MAPS|ACCESS|AUTH)_KEYS?(_|$)'
    r'|(^|_)(APIKEYS?|SECRETKEYS?|PRIVATEKEYS?|ACCESSKEYS?)(_|$)'
    r'|(^|_)AUTH_HEADERS?(_|$)'
    r'|(^|_)(SENSITIVE|REDACT(ED|ION)?|PASSPHRASE|HMAC|COOKIE|AUTHORIZATION)(_|$)'
    # An admin list or an email allowlist has no distinctive VALUE shape
    # for _SECRET_VALUE_RES to catch, unlike a DSN or a PEM block, and
    # shipping authorisation data to the browser is a classic mistake.
    r'|(^|_)(ADMINS?|ALLOWLIST|WHITELIST|DENYLIST|BLOCKLIST)(_|$)'
    r'|(^|_)EMAILS?(_|$)', re.IGNORECASE)

# Nested keys are camelCase and are matched word-by-word against a deliberately
# NARROWER set than the top-level regex. Note what is absent: bank/account.
# A public dropdown of bank *names* ({'bank': 'BDO Unibank'}) must stay
# shippable, and a display key is a wire contract that cannot just be renamed.
_NESTED_SECRET_WORDS = {
    'secret', 'secrets', 'token', 'password', 'passwords', 'passwd',
    'credential', 'credentials', 'private', 'salt', 'signature', 'signatures',
    'pin', 'otp', 'apikey', 'apikeys', 'bearer',
    # Blocked at top level by _SECRETISH_RE; there was no reason for a nested
    # {'cookie': 'sid=...'} to be treated more leniently than COOKIE.
    'cookie', 'cookies', 'authorization', 'hmac', 'sensitive', 'passphrase',
}
_TOKENS_QUALIFIERS = {'access', 'auth', 'refresh', 'bearer'}
_KEY_QUALIFIERS = {
    'api', 'secret', 'private', 'signing', 'encryption', 'access', 'auth',
    'maps',
}
_NAME_WORD_RE = re.compile(r'[A-Z]+(?![a-z])|[A-Z][a-z]*|[a-z]+|[0-9]+')

# High-signal credential shapes, checked on every string leaf. Name matching
# alone is not enough: a real key under a benign name ships otherwise.
_SECRET_VALUE_RES = [
    (re.compile(r'^sk-'), 'an API secret key'),
    (re.compile(r'^AIza[0-9A-Za-z_-]{30,}'), 'a Google API key'),
    (re.compile(r'^gh[pousr]_'), 'a GitHub token'),
    (re.compile(r'^xox[baprs]-'), 'a Slack token'),
    (re.compile(r'-----BEGIN '), 'a PEM private key'),
    (re.compile(r'^ey[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.'), 'a JWT'),
    # A connection string with an inline password is the likeliest way a
    # real credential reaches this file under a benign name
    # (DATA_SOURCE_URL, DB_DSN); the name guard would never see it.
    (re.compile(r'://[^/\s:@]+:[^/\s@]+@'),
     'a connection string with an embedded password'),
    # Stripe uses sk_live_ / sk_test_ with an UNDERSCORE; the ^sk- rule
    # above only matches OpenAI's hyphenated shape.
    (re.compile(r'^sk_(live|test)_'), 'a Stripe secret key'),
    (re.compile(r'(AKIA|ASIA)[0-9A-Z]{16}'), 'an AWS access key id'),
    (re.compile(r'^GOCSPX-'), 'a Google OAuth client secret'),
    (re.compile(r'^SG\.[A-Za-z0-9_-]{16,}'), 'a SendGrid API key'),
    (re.compile(r'^(Basic|Bearer)\s+[A-Za-z0-9+/=._-]{16,}'),
     'an Authorization header'),
]
# A run of 12+ digits, once spaces and dashes are removed, reads as a bank or
# card account number. The threshold is 12 and NOT 11 on purpose: an 11-digit
# PH mobile / GCash number is a legitimate public constant (a store contact
# number) and must stay shippable. This is a tripwire, not a proof of absence
# — a shorter account number or an unrecognised key format still gets through.
_DIGIT_RUN_RE = re.compile(r'\d{12,}')
_UNSPACED_RE = re.compile(r'[\s-]')

# JS numbers are IEEE-754 doubles, so an integer past 2**53-1 emitted as a bare
# TS number literal silently loses precision in the browser.
_JS_MAX_SAFE_INT = 2**53 - 1


def _name_words(name: str) -> list[str]:
    """Lowercased words of a key, split on _ - and camelCase boundaries."""
    return [w.lower() for part in re.split(r'[_-]', name)
            for w in _NAME_WORD_RE.findall(part)]


def _nested_key_is_secretish(key: str) -> bool:
    """Whether a key *inside* a shared constant reads as a credential."""
    words = _name_words(key)
    if any(w in _NESTED_SECRET_WORDS for w in words):
        return True
    if 'tokens' in words and any(w in _TOKENS_QUALIFIERS for w in words):
        return True
    return any(a in _KEY_QUALIFIERS and b in ('key', 'keys')
               for a, b in zip(words, words[1:]))


def _browser_publication_error(where: str, what: str) -> ValueError:
    return ValueError(
        f'sharedConstants: {where} {what}, and this file is published to every '
        'browser. If this must stay server-only, prefix the constant with "_" '
        'or move it to another module.')


def _assert_json_safe(name: str, value: Any, path: str = '') -> None:
    """Recursive allow-list check on a shared constant's value.

    Names the constant AND the path inside it, so the failure reads
    'DELIVERY_VEHICLES[3].maxCbm is a Decimal' rather than an opaque
    'Object of type Decimal is not JSON serializable'.
    """
    where = f'{name}{path}'
    if value is None:
        return
    # bool first: it is an int subclass, and the safe-integer check below must
    # not run on True/False.
    if isinstance(value, bool):
        return
    if isinstance(value, int):
        # Deliberately NOT digit-run checked. A 12+ digit *int* is far more
        # likely a legitimate limit than an account number — 2**53-1 is 16
        # digits — and an account number stored as an int has already lost its
        # leading zeros, so the str branch below is where that shape really
        # appears. Blocking ints here false-positived on MAX_SAFE_QUANTITY.
        if abs(value) > _JS_MAX_SAFE_INT:
            raise ValueError(
                f'sharedConstants: {where} is {value}, which is outside '
                f"JavaScript's safe integer range (±{_JS_MAX_SAFE_INT}). A "
                'bare TS number literal would silently lose precision in the '
                'browser — emit it as a string instead.')
        return
    if isinstance(value, str):
        for pattern, what in _SECRET_VALUE_RES:
            if pattern.search(value):
                raise _browser_publication_error(where, f'looks like {what}')
        if _DIGIT_RUN_RE.search(_UNSPACED_RE.sub('', value)):
            raise _browser_publication_error(
                where, 'contains a 12+ digit run, which reads as a bank or '
                'card account number')
        return
    if isinstance(value, float):
        if value != value or value in (float('inf'), float('-inf')):
            raise TypeError(
                f'sharedConstants: {where} is {value!r}; NaN and Infinity have '
                'no JSON literal. Use a finite number or None.')
        return
    if isinstance(value, (list, tuple)):
        for i, item in enumerate(value):
            _assert_json_safe(name, item, f'{path}[{i}]')
        return
    if isinstance(value, dict):
        for key, item in value.items():
            if not isinstance(key, str):
                raise TypeError(
                    f'sharedConstants: {where} has a non-string key {key!r}. '
                    'JSON object keys must be strings.')
            if _nested_key_is_secretish(key):
                raise _browser_publication_error(f'{where}.{key}',
                                                 'looks like a secret')
            _assert_json_safe(name, item, f'{path}.{key}')
        return
    hint = {
        'datetime': 'call .isoformat()',
        'date': 'call .isoformat()',
        'Decimal': 'use float(...)',
        'set': 'use sorted(list(...))',
        'frozenset': 'use sorted(list(...))',
        'Pattern': 'use .pattern',
    }.get(
        type(value).__name__,
        'convert it to a plain str/int/float/bool/None/list/dict — but decide '
        'FIRST whether it belongs in a file every browser downloads, because '
        'flattening a model (model_dump()) is also how a server-only value '
        'such as AUTHORIZED_PAYMENT_CHANNELS would end up published')
    raise TypeError(f'sharedConstants: {where} is a {type(value).__name__}, '
                    f'which is not JSON-able — {hint}.')


def renderSharedConstantsTS() -> str:
    """Render sharedConstants.py's public values as TypeScript. Pure."""
    chunks = [_TS_BANNER]
    for name, value in vars(sharedConstants).items():
        if name.startswith('_'):
            continue
        if isinstance(value, types.ModuleType):
            continue
        if isinstance(value, (types.FunctionType, type)):
            # Silently skipping would drop it from the TS with both sides
            # agreeing it is absent, so the drift test could never catch it.
            raise ValueError(
                f'sharedConstants: {name!r} is a {type(value).__name__}, which cannot be shared. Prefix it with "_" if it '
                'is a server-only helper.')
        if not _TS_NAME_RE.match(name) or name in _TS_RESERVED:
            raise ValueError(f'sharedConstants: {name!r} is not a usable '
                             'TypeScript identifier')
        if _SECRETISH_RE.search(name):
            raise _browser_publication_error(name, 'looks like a secret')
        _assert_json_safe(name, value)
        literal = json.dumps(value,
                             indent=2,
                             ensure_ascii=False,
                             allow_nan=False)
        # `as const` is a uniform suffix needing no knowledge of the value,
        # so the emitter stays a dumb copier. On the client it keeps the
        # values immutable and lets a union type be derived straight from a
        # shared list instead of retyping the server's Literal.
        # `null as const` is TS1355 ('const' assertions apply only to enum
        # members and string/number/boolean/array/object literals), and the
        # docstring advertises None as legal. Without this the generator,
        # --constants-only and the drift test all stay green while the
        # client build breaks far from the one-line Python edit. Nested
        # nulls are fine: [null, 1] as const compiles.
        suffix = '' if value is None else ' as const'
        chunks.append(f'export const {name} = {literal}{suffix};\n')
    return '\n'.join(chunks)
